"""Turns the Adaption download into the warning message library.
Run in the backend folder:  python import_adaption.py [adaption_output.csv] [output_folder]
Makes app/data/messages.json and adaption_review.csv (give that sheet to native speakers)."""
import csv, json, os, re, sys, unicodedata

SRC = sys.argv[1] if len(sys.argv) > 1 else "adaption_output.csv"
OUT_DIR = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "app", "data")
NON_LATIN = {"hi", "bn", "mr", "ta", "te", "ur", "gu", "pa", "ml", "kn", "or", "as", "ne"}


def ascii_digits(s):
    """Turns native digits (like १ or ১) into 0-9 so key presses can be checked."""
    out = ""
    for ch in s:
        try:
            out += str(unicodedata.digit(ch))
        except ValueError:
            out += ch
    return out


def has_key(s, k):
    return re.search(rf"(?<!\d){k}(?!\d)", ascii_digits(s)) is not None


def problems_for(code, en, tr):
    p = []
    if ("{ward}" in en) != ("{ward}" in tr):
        p.append("{ward} placeholder changed")
    for k in ("1", "2"):
        if has_key(en, k) and not has_key(tr, k):
            p.append(f"key {k} missing")
    ratio = len(tr) / max(len(en), 1)
    if ratio < 0.4 or ratio > 2.8:
        p.append(f"length ratio {ratio:.1f}")
    if tr.strip() == en.strip():
        p.append("not translated")
    elif code in NON_LATIN:
        letters = re.sub(r"\{ward\}", "", tr)
        latin = sum(c.isascii() and c.isalpha() for c in letters)
        if latin > 0.5 * max(sum(c.isalpha() for c in letters), 1):
            p.append("looks untranslated")
    return p


with open(SRC, encoding="utf-8-sig", newline="") as f:
    rows = list(csv.DictReader(f))
if not rows:
    sys.exit("The file is empty.")

english = {}
for r in rows:
    if not (r.get("target_language") or "").strip():
        english[(r.get("scenario") or r.get("original_context") or "").strip()] = (r.get("message_en") or "").strip()
if not english:
    sys.exit("Could not find the English rows. Columns are: " + ", ".join(rows[0].keys()))

library = {"en": {k: v for k, v in english.items() if k}}
review, counts, flagged = [], {}, 0
for r in rows:
    code = (r.get("target_language_code") or "").strip().lower().replace("_", "-").split("-")[0]
    if not code:
        continue
    key = next((k for k in ((r.get("scenario") or "").strip(), (r.get("original_context") or "").strip()) if k in english), None)
    if not key:
        print("Skipped a row: cannot match it to an English message.")
        continue
    cands = [(c, (r.get(c) or "").strip()) for c in ("message_en", "enhanced_completion")]
    cands = [(c, t) for c, t in cands if t]
    if not cands:
        continue
    scored = [(problems_for(code, english[key], t), c, t) for c, t in cands]
    best = next((s for s in scored if not s[0]), scored[0])  # first one that passes the checks
    probs, col, text = best
    alt = next((t for p, c, t in scored if t != text), "")
    library.setdefault(code, {})[key] = text
    counts[code] = counts.get(code, 0) + 1
    flagged += bool(probs)
    review.append({"language": code, "scenario": key, "english": english[key], "chosen": text,
                   "chosen_column": col, "alternate": alt, "automatic_problems": "; ".join(probs), "reviewer_ok": ""})

library["_meta"] = {"status": "AI-generated by Adaption Adaptive Data (Translate). Pending native-speaker review.",
                    "source": os.path.basename(SRC)}
os.makedirs(OUT_DIR, exist_ok=True)
with open(os.path.join(OUT_DIR, "messages.json"), "w", encoding="utf-8") as f:
    json.dump(library, f, ensure_ascii=False, indent=2)
with open("adaption_review.csv", "w", encoding="utf-8-sig", newline="") as f:
    w = csv.DictWriter(f, fieldnames=list(review[0].keys()) if review else ["language"])
    w.writeheader()
    w.writerows(review)

print(f"English messages: {len(english)}")
for c, n in sorted(counts.items()):
    print(f"  {c}: {n} messages" + ("" if n == len(english) else f"  (expected {len(english)})"))
print(f"Rows flagged by automatic checks: {flagged}")
for r in review:
    if r["automatic_problems"]:
        print(f"  - {r['language']} / {r['scenario']}: {r['automatic_problems']}")
print("Saved app/data/messages.json and adaption_review.csv (needs native-speaker review).")
